"""Zip the Godot addon for a GitHub release and the Godot Asset Library ("Custom" download URL).

    python tools/package_godot_addon.py [--out dist]

Writes dist/spritekiln-godot-<version>.zip holding spritekiln-godot-<version>/addons/spritekiln/ (Godot's
installer drops the root folder). Fails when plugin.cfg and the Python package disagree on the version.
"""

import argparse
import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADDON = os.path.join(ROOT, 'integrations', 'godot', 'addons', 'spritekiln')


def versions():
    with open(os.path.join(ROOT, 'spritekiln', '__init__.py'), encoding='utf-8') as fh:
        package = re.search(r"__version__ = '([^']+)'", fh.read()).group(1)
    with open(os.path.join(ADDON, 'plugin.cfg'), encoding='utf-8') as fh:
        plugin = re.search(r'^version="([^"]+)"', fh.read(), re.M).group(1)
    return package, plugin


def package(out):
    version, plugin = versions()
    if version != plugin:
        raise SystemExit(f'plugin.cfg says {plugin}, the package says {version}: bump them together')
    top = f'spritekiln-godot-{version}'
    path = os.path.join(out, f'{top}.zip')
    os.makedirs(out, exist_ok=True)
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        for name in sorted(os.listdir(ADDON)):
            if name.endswith('.import') or name.endswith('.uid'):
                continue  # generated by Godot in the project, never shipped
            z.write(os.path.join(ADDON, name), f'{top}/addons/spritekiln/{name}')
    return path


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('--out', default=os.path.join(ROOT, 'dist'))
    print(package(p.parse_args(argv).out))


if __name__ == '__main__':
    sys.exit(main())
